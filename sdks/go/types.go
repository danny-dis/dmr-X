// ── Stream Chunk Types ───────────────────────────────────────────

// StreamChunkType indicates the type of streaming chunk.
type StreamChunkType string

const (
	StreamChunkToken StreamChunkType = "token"
	StreamChunkDone  StreamChunkType = "done"
	StreamChunkError StreamChunkType = "error"
)

// StreamChunk is a single chunk from a streaming response.
type StreamChunk struct {
	Type  StreamChunkType `json:"type"`
	Data  json.RawMessage `json:"data"`
	Index int             `json:"index"`
}

// TokenData contains the content delta in a token stream chunk.
type TokenData struct {
	Content    *string     `json:"content,omitempty"`
	ToolCalls []ToolCall  `json:"tool_calls,omitempty"`
	Role      string      `json:"role,omitempty"`
}

// DoneData contains completion metadata.
type DoneData struct {
	RequestID    string     `json:"requestId"`
	ModelID      string     `json:"modelId"`
	FinishReason string     `json:"finishReason"`
	Usage        *TokenUsage `json:"usage,omitempty"`
}

// ErrorData contains error information in an error chunk.
type ErrorData struct {
	Code    string `json:"code"`
	Message string `json:"message"`
}
