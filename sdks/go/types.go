package dmrx

import "encoding/json"

// ── Modality ─────────────────────────────────────────────────────

// Modality represents the AI modality — what kind of content the model processes.
type Modality string

const (
	ModalityLLM             Modality = "llm"
	ModalityDiffusion       Modality = "diffusion"
	ModalityEmbedding       Modality = "embedding"
	ModalityAudioTTS        Modality = "audio_tts"
	ModalityAudioSTT        Modality = "audio_stt"
	ModalityAudioSeparation Modality = "audio_separation"
	ModalityVideo           Modality = "video"
	ModalityVideoAnalysis   Modality = "video_analysis"
	ModalityMusic           Modality = "music"
	ModalityReranking       Modality = "reranking"
	ModalityModeration      Modality = "moderation"
	ModalityCodeCompletion  Modality = "code_completion"
	ModalityOCR             Modality = "ocr"
	ModalityImageUpscaling  Modality = "image_upscaling"
	ModalityImageInpainting Modality = "image_inpainting"
	ModalityVision          Modality = "vision"
	Modality3D              Modality = "3d"
)

// QualityTarget controls the provider routing strategy.
type QualityTarget string

const (
	QualityFrontier QualityTarget = "frontier"
	QualityBalanced QualityTarget = "balanced"
	QualityEconomy  QualityTarget = "economy"
)

// ── Token Usage ──────────────────────────────────────────────────

// TokenUsage represents token usage statistics.
type TokenUsage struct {
	PromptTokens     int `json:"prompt_tokens"`
	CompletionTokens int `json:"completion_tokens"`
	TotalTokens      int `json:"total_tokens"`
}

// ── Messages ─────────────────────────────────────────────────────

// MessageRole represents the role of a message participant.
type MessageRole string

const (
	RoleSystem    MessageRole = "system"
	RoleUser      MessageRole = "user"
	RoleAssistant MessageRole = "assistant"
	RoleTool      MessageRole = "tool"
)

// ContentPart represents a piece of message content (text, image, or audio).
type ContentPart struct {
	Type       string           `json:"type"`
	Text       string           `json:"text,omitempty"`
	ImageURL   *ImageURLContent `json:"image_url,omitempty"`
	InputAudio *AudioContent    `json:"input_audio,omitempty"`
}

// ImageURLContent represents an image URL reference in a message.
type ImageURLContent struct {
	URL    string `json:"url"`
	Detail string `json:"detail,omitempty"` // auto, low, high
}

// AudioContent represents inline audio data in a message.
type AudioContent struct {
	Data   string `json:"data"`
	Format string `json:"format"` // wav, mp3
}

// ToolCall represents a function call generated by the model.
type ToolCall struct {
	ID       string        `json:"id"`
	Type     string        `json:"type"` // "function"
	Function ToolCallFunc  `json:"function"`
}

// ToolCallFunc represents the function details in a tool call.
type ToolCallFunc struct {
	Name      string `json:"name"`
	Arguments string `json:"arguments"` // JSON string
}

// Message represents a chat message in the conversation.
type Message struct {
	Role       MessageRole  `json:"role"`
	Content    interface{}  `json:"content,omitempty"` // string or []ContentPart
	Name       string       `json:"name,omitempty"`
	ToolCalls  []ToolCall   `json:"tool_calls,omitempty"`
	ToolCallID string       `json:"tool_call_id,omitempty"`
}

// Tool represents a tool/function definition available to the model.
type Tool struct {
	Type     string         `json:"type"` // "function"
	Function ToolDefinition `json:"function"`
}

// ToolDefinition represents the definition of a callable function.
type ToolDefinition struct {
	Name        string          `json:"name"`
	Description string          `json:"description,omitempty"`
	Parameters  json.RawMessage `json:"parameters,omitempty"`
}

// ── Chat Completion Request / Response ───────────────────────────

// ChatCompletionRequest is the request body for POST /v1/chat/completions.
type ChatCompletionRequest struct {
	Model               string              `json:"model"`
	Messages            []Message           `json:"messages"`
	Temperature         *float64            `json:"temperature,omitempty"`
	MaxTokens           *int                `json:"max_tokens,omitempty"`
	TopP                *float64            `json:"top_p,omitempty"`
	FrequencyPenalty    *float64            `json:"frequency_penalty,omitempty"`
	PresencePenalty     *float64            `json:"presence_penalty,omitempty"`
	Stop                interface{}         `json:"stop,omitempty"` // string or []string
	Stream              bool                `json:"stream"`
	Tools               []Tool              `json:"tools,omitempty"`
	ToolChoice          interface{}         `json:"tool_choice,omitempty"`
	ResponseFormat      *ResponseFormat     `json:"response_format,omitempty"`
	Seed                *int                `json:"seed,omitempty"`
	N                   *int                `json:"n,omitempty"`
	User                string              `json:"user,omitempty"`

	// DMR-X specific routing parameters
	Quality            QualityTarget `json:"quality,omitempty"`
	ProviderPreference []string      `json:"provider_preference,omitempty"`
	ProviderBlacklist  []string      `json:"provider_blacklist,omitempty"`
	LatencyTarget      interface{}   `json:"latency_target,omitempty"` // int or string
	CostTarget         interface{}   `json:"cost_target,omitempty"`   // float or string
	LocalFirst         *bool         `json:"local_first,omitempty"`
	RequirePrivacy     *bool         `json:"require_privacy,omitempty"`
}

// ResponseFormat specifies the format of the model's response.
type ResponseFormat struct {
	Type string `json:"type"` // "text" or "json_object"
}

// ChatCompletionResponse is the response from POST /v1/chat/completions.
type ChatCompletionResponse struct {
	ID        string                 `json:"id"`
	Object    string                 `json:"object"` // "chat.completion"
	Created   int64                  `json:"created"`
	Model     string                 `json:"model"`
	Choices   []ChatCompletionChoice `json:"choices"`
	Usage     *TokenUsage            `json:"usage,omitempty"`
	Provider  string                 `json:"provider,omitempty"`
	LatencyMs float64                `json:"latency_ms,omitempty"`
}

// ChatCompletionChoice represents a single completion choice.
type ChatCompletionChoice struct {
	Index        int             `json:"index"`
	Message      Message         `json:"message"`
	FinishReason string          `json:"finish_reason,omitempty"`
}

